// Processes the customer's mattress sale.
private void processSale() {

    // Get the customer's name.
    String customerName = txtCustomerName.getText().trim();

    // Get the selected mattress product.
    String productName = cmbProduct.getSelectedItem().toString();

    // Validate the customer name.
    if (customerName.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter the customer name.");
        return;
    }

    // Declare a variable for the product price.
    double price;

    try {
        // Convert the entered price into a double.
        price = Double.parseDouble(txtPrice.getText().trim());

        // Check that the price is greater than zero.
        if (price <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Please enter a price greater than zero.");
            return;
        }

    } catch (NumberFormatException e) {

        // Display an error if the price is not numeric.
        JOptionPane.showMessageDialog(this,
                "Please enter a valid product price.");
        return;
    }

    // Create an object of ProductCalculations.
    ProductCalculations calculation =
            new ProductCalculations(price);

    // Calculate VAT, commission and total sales.
    double vat = calculation.GetVat();
    double commission = calculation.GetCommission();
    double total = calculation.GetTotal();

    // Display the calculated amounts.
    txtVat.setText(String.valueOf(vat));
    txtCommission.setText(String.valueOf(commission));
    txtTotal.setText(String.valueOf(total));

    // Save the transaction to the data.txt file.
    saveSale(customerName, productName, vat, commission, total);
}

// Saves the transaction details to data.txt.
private void saveSale(String customerName, String productName,
        double vat, double commission, double total) {

    // Open the file in append mode to preserve previous transactions.
    try (PrintWriter writer =
            new PrintWriter(new FileWriter("data.txt", true))) {

        // Write the sales information to the file.
        writer.println("DATA LOG");
        writer.println("*******************************");
        writer.println("Customer Name: " + customerName);
        writer.println("Product: " + productName);
        writer.println("VAT: R " + vat);
        writer.println("COMMISSION: R " + commission);
        writer.println("TOTAL: R " + total);
        writer.println("*******************************");
        writer.println();

        // Confirm that the transaction was saved.
        JOptionPane.showMessageDialog(this,
                "Sale processed and saved successfully.");

    } catch (IOException e) {

        // Display an error if the file cannot be saved.
        JOptionPane.showMessageDialog(this,
                "Error saving file: " + e.getMessage());
    }
}

